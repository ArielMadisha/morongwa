function normalizeTokens(s: string): string[] {
  return String(s || "")
    .toLowerCase()
    .replace(/[0-9_]+/g, " ")
    .replace(/[^a-z\s]/g, " ")
    .split(/\s+/)
    .filter((t) => t.length >= 2);
}

function looksFemaleBySuffix(token: string): boolean {
  if (token.length < 4) return false;
  if (MALE.has(token)) return false;
  // Common feminine endings for given names (priyanka, jessica, etc.).
  if (/(ine|elle|ette|een|ia|ya)$/i.test(token)) return true;
  if (token.endsWith("a") || token.endsWith("i")) return true;
  return false;
}

/**
 * Infer male/female from name and/or username (e.g. priyanka2 → priyanka → female).
 * Defaults to male when unknown (same as bulk signup).
 */
export function inferUserGender(givenNameRaw: string, surnameOrUsername = ""): InferredGender {
  const given = normalizeTokens(givenNameRaw);
  const extra = normalizeTokens(surnameOrUsername);

  let femaleScore = 0;
  let maleScore = 0;
  const scoreTokens = (tokens: string[], weight: number) => {
    for (const t of tokens) {
      if (FEMALE.has(t)) femaleScore += weight;
      if (MALE.has(t)) maleScore += weight;
      if (looksFemaleBySuffix(t) && !MALE.has(t)) femaleScore += Math.max(1, Math.floor(weight / 2));
    }
  };
  scoreTokens(given, 3);
  scoreTokens(extra, 2);

  if (femaleScore > maleScore) return "female";
  if (maleScore > femaleScore) return "male";
  return "male";
}
